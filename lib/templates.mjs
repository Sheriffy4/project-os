export function buildKickoffPrompt(project) {
  const meta = project.meta || {};
  return `# Быстрый старт проекта «${project.name}»

Ты — концепт-дизайнер и технический консультант. Помоги довести проект от идеи до вертикального среза, не раздувая скоуп.

## Вводные
- Название: ${project.name}
- Жанр: ${meta.genre || 'не указан'}
- Платформы: ${Array.isArray(meta.platforms) ? meta.platforms.join(', ') : meta.platforms || 'не указаны'}
- Референсы: ${Array.isArray(meta.references) ? meta.references.join(', ') : meta.references || 'не указаны'}
- Питч: ${project.description || 'не указан'}

## Твоя задача на этот шаг
1. Сформулируй питч в 3–5 предложениях: что это, для кого, почему в это будут играть.
2. Назови 3–5 столпов дизайна в порядке приоритета.
3. Опиши кор-луп одним абзацем и схемой.
4. Назови 5 главных рисков и способ проверки каждого.
5. Предложи вертикальный срез: что входит, что не входит, сколько времени займёт.
6. Задай не более 5 вопросов, без ответов на которые нельзя двигаться дальше.

## Формат
Markdown. Каждый пункт — атомарный, без воды. Если данных не хватает — пиши «нужно уточнить», не выдумывай.

## Следующий шаг
После ответа мы сохраним решения в Project OS и отправим по агенту на каждый раздел: ${DEFAULT_SECTIONS.map((s) => s.name).join(', ')}.`;
}

